ANALYZE_SOURCE = r'''
def analyze(self, frame, full_size=None):
    top=self.normalize_top(frame,full_size)
    self.last_top=top
    self.last_extraction=self.extraction_features(top)
    scores=self.scores_top(top)
    self.last_extraction['bar_frames']=self.last_features.get('bar_frames',0)
    self.last_extraction['body_shape']=self.last_features.get('body_shape',0)
    gray=cv2.cvtColor(top,cv2.COLOR_BGR2GRAY)
    mean_luma=float(gray.mean())
    hist=cv2.calcHist([gray],[0],None,[256],[0,256]).ravel()
    p99_luma=float(np.searchsorted(np.cumsum(hist),
        .99*(gray.size-1),side='left'))
    if self.last_extraction.get('end'):
        self.last_interface='M'
        self.last_menu_features=dict(interface='M',interface_score=1.,
            inventory=0.,pause=0.,skipped_for_combat=False,
            extraction_banner=False,blackout=False,
            end_score=self.last_extraction['end_score'],
            mean_luma=mean_luma,p99_luma=p99_luma)
        return scores,1.
    if mean_luma<=4. and p99_luma<=10.:
        self.last_extraction['blackout']=True
        self.last_interface='Z'
        self.last_menu_features=dict(interface='Z',interface_score=1.,
            inventory=0.,pause=0.,skipped_for_combat=False,
            extraction_banner=False,blackout=True,
            mean_luma=mean_luma,p99_luma=p99_luma)
        return scores,1.
    if self.last_extraction.get('banner'):
        self.last_interface='B'
        self.last_menu_features=dict(interface='B',interface_score=1.,
            inventory=0.,pause=0.,skipped_for_combat=False,
            extraction_banner=True)
        return scores,1.
    # Strong HUD evidence skips the menu pass. Weak HUD evidence (.22-.48)
    # still runs menu detection first so a fading hotbar cannot mask C/D/...;
    # menu_score_top falls back to A when no menu template matches.
    if self.last_features.get('combat_score',0)>=.48:
        self.last_interface='A'
        self.last_menu_features=dict(interface='A',
            interface_score=self.last_features['combat_score'],
            inventory=0.,pause=0.,skipped_for_combat=True,
            extraction_banner=False)
        return scores,0.
    return scores,self.menu_score_top(top,gray)
'''

