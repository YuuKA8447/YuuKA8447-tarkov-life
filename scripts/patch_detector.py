        self.last_interface='A'
        self.last_menu_features=dict(interface='A',interface_score=combat,
            combat=combat,console=console,tab_scores=tab_scores,
            tab_match=best_tab,inventory=0.,pause=pause,
            extraction_banner=extraction_banner,skipped_for_combat=True)
        return 0.
