def load_templates():
    metadata = json.loads(
        (TEMPLATES_DIR / "templates.json").read_text(encoding="utf-8")
    )
    items = metadata["templates"]
    missing = [name for name in REQUIRED if name not in items]
    if missing:
        raise RuntimeError(f"templates.json is missing: {missing}")
    blobs = {}
    meta = {}
    for name in REQUIRED:
        item = items[name]
        data = (TEMPLATES_DIR / item["file"]).read_bytes()
        if len(data) != item["bytes"]:
            raise RuntimeError(f"{name} size changed: {len(data)}")
        blobs[name] = data
        box = item["box"]
        meta[name] = (box[0], box[1], box[2], box[3], item["margin"])
    return blobs, meta


def parse_archive(buf):
    cp = buf.rfind(COOKIE)
    if cp < 0:
        raise RuntimeError("cookie not found")
    magic, pkg_len, toc_off, toc_len, pyver, pylib = struct.unpack(
        "!8sIIii64s", buf[cp:cp + 88]
    )
    tail = len(buf) - cp - 88
    overlay = len(buf) - (pkg_len + tail)
    toc = bytes(buf[overlay + toc_off:overlay + toc_off + toc_len])
    entries = {}
    pos = 0
    while pos < len(toc):
        es, = struct.unpack("!i", toc[pos:pos + 4])
        epos, cmprsd, uncmprsd, flag, typ, name = struct.unpack(
            "!IIIBc" + str(es - 18) + "s", toc[pos + 4:pos + es]
        )
        nm = name.decode("utf-8", "replace").rstrip("\0")
        entries[nm] = {
            "pos": epos, "cmprsd": cmprsd, "uncmprsd": uncmprsd,
            "flag": flag, "type": typ,
        }
        pos += es
    return overlay, entries


def find_code(code, name):
    for value in code.co_consts:
        if isinstance(value, types.CodeType):
            if value.co_name == name:
                return value
            found = find_code(value, name)
            if found is not None:
                return found
    return None


def find_class_method(code, class_name, method_name):
    for value in code.co_consts:
        if isinstance(value, types.CodeType) and value.co_name == class_name:
            for item in value.co_consts:
                if isinstance(item, types.CodeType) and item.co_name == method_name:
                    return item
    return None


def method_from_source(source, method_name):
    compiled = compile(source, "detector.py", "exec")
    method = find_code(compiled, method_name)
    if method is None:
        raise RuntimeError(f"{method_name} source compile failed")
    return method


def replace_class_method(code, class_name, method_name, new):
    consts = []
    hit = False
    for value in code.co_consts:
        if isinstance(value, types.CodeType) and value.co_name == class_name:
            inner = []
            for item in value.co_consts:
                if isinstance(item, types.CodeType) and item.co_name == method_name:
                    inner.append(new)
                    hit = True
                else:
                    inner.append(item)
            consts.append(value.replace(co_consts=tuple(inner)))
        else:
            consts.append(value)
    return code.replace(co_consts=tuple(consts)), hit


def replace_module_function(code, name, new):
    """Replace a top-level function only; nested classes stay untouched."""
    consts = []
    hit = False
    for value in code.co_consts:
        if isinstance(value, types.CodeType) and value.co_name == name:
            consts.append(new)
            hit = True
        else:
            consts.append(value)
    return code.replace(co_consts=tuple(consts)), hit


def main():
    buf = SRC.read_bytes()
    overlay, entries = parse_archive(buf)
    pyz = entries["PYZ.pyz"]
    pyz_bytes = bytes(buf[overlay + pyz["pos"]:overlay + pyz["pos"] + pyz["cmprsd"]])
    toc_pos = struct.unpack(">i", pyz_bytes[8:12])[0]
    toc = dict(marshal.loads(pyz_bytes[toc_pos:]))
    _, pos, length = toc["detector"]
    if length != SLOT:
        print("warning: detector slot is", length, "expected", SLOT)
    blob = zlib.decompress(pyz_bytes[pos:pos + length])
    code = marshal.loads(blob)

    blobs, meta = load_templates()
    init_source = INIT_SOURCE.replace("__TEMPLATE_BLOBS__", repr(blobs))
    init_source = init_source.replace("__TEMPLATE_META__", repr(meta))

    new_init = method_from_source(init_source, "__init__")
    new_normalize = method_from_source(NORMALIZE_SOURCE, "normalize_top")
    new_scores = method_from_source(SCORES_SOURCE, "scores_top")
    new_extract = method_from_source(EXTRACTION_SOURCE, "extraction_features")
    new_menu = method_from_source(MENU_SOURCE, "menu_score_top")
    new_analyze = method_from_source(ANALYZE_SOURCE, "analyze")
    new_reset = method_from_source(GUARD_RESET_SOURCE, "reset")
    new_update = method_from_source(GUARD_UPDATE_SOURCE, "update")
    new_arm = find_code(compile(ARM_SOURCE, "detector.py", "exec"),
                        "start_hud_evidence")
    if new_arm is None:
        raise RuntimeError("start_hud_evidence source compile failed")

    old_gate = find_class_method(code, "Gate", "update")
    old_guard = find_class_method(code, "ExtractionGuard", "update")
    old_reset = find_class_method(code, "ExtractionGuard", "reset")
    if old_gate is None or old_guard is None or old_reset is None:
        raise RuntimeError("guard methods are missing from the base module")

    module, hit_arm = replace_module_function(code, "start_hud_evidence", new_arm)
    module, hit_init = replace_class_method(module, "Detector", "__init__", new_init)
    module, hit_norm = replace_class_method(
        module, "Detector", "normalize_top", new_normalize
    )
    module, hit_scores = replace_class_method(
        module, "Detector", "scores_top", new_scores
    )
